from machine import Pin, PWM, ADC
import time

# =============================================================================
# ΡΥΘΜΙΣΕΙΣ ΚΙΝΗΤΗΡΩΝ
# Χρησιμοποιούμε PWM (Pulse Width Modulation) για να ελέγχουμε την ταχύτητα
# και κατεύθυνση των κινητήρων μέσω του driver DRV8835.
# Κάθε κινητήρας έχει 2 pins (IN1, IN2):
#   - IN1 > 0, IN2 = 0 → μπροστά
#   - IN1 = 0, IN2 > 0 → πίσω
#   - IN1 = IN2 = 0    → stop
# =============================================================================
motorA_in1 = PWM(Pin(16))  # Κινητήρας Α (Αριστερά) — είσοδος 1
motorA_in2 = PWM(Pin(17))  # Κινητήρας Α (Αριστερά) — είσοδος 2
motorB_in1 = PWM(Pin(14))  # Κινητήρας Β (Δεξιά)    — είσοδος 1
motorB_in2 = PWM(Pin(15))  # Κινητήρας Β (Δεξιά)    — είσοδος 2

# Ορισμός συχνότητας PWM στα 1000 Hz για όλους τους κινητήρες
for m in [motorA_in1, motorA_in2, motorB_in1, motorB_in2]:
    m.freq(1000)

# =============================================================================
# ΡΥΘΜΙΣΕΙΣ ΑΙΣΘΗΤΗΡΩΝ
# Χρησιμοποιούμε 5 υπέρυθρους (IR) αισθητήρες διατεταγμένους οριζόντια.
# IR1 και IR5 (ακραίοι) είναι ψηφιακοί — επιστρέφουν 0 ή 1.
# IR2, IR3, IR4 (κεντρικοί) είναι αναλογικοί ADC — επιστρέφουν 0–65535.
# Μαύρο = χαμηλή τιμή ADC / ψηφιακό 0 (με PULL_UP → value()==0 σημαίνει ενεργός)
# Λευκό = υψηλή τιμή ADC / ψηφιακό 1
# =============================================================================
ir1 = Pin(2, Pin.IN, Pin.PULL_UP)  # Ακραίος αριστερά  — ψηφιακός
ir2 = ADC(Pin(28))                 # Δεύτερος αριστερά — αναλογικός
ir3 = ADC(Pin(27))                 # Κεντρικός          — αναλογικός
ir4 = ADC(Pin(26))                 # Δεύτερος δεξιά    — αναλογικός
ir5 = Pin(6, Pin.IN, Pin.PULL_UP)  # Ακραίος δεξιά     — ψηφιακός

# =============================================================================
# ΠΑΡΑΜΕΤΡΟΙ PD CONTROLLER
# Ο PD controller διορθώνει την κατεύθυνση του ρομπότ βάσει δύο όρων:
#   P (Proportional): ανάλογος του τρέχοντος σφάλματος
#   D (Derivative):   ανάλογος της μεταβολής του σφάλματος (ταχύτητα αλλαγής)
# correction = P + D → προστίθεται/αφαιρείται από την ταχύτητα κάθε κινητήρα
# =============================================================================
base_speed = 35000   # Βασική ταχύτητα κινητήρων (εύρος: 0–65535)
Kp         = 8000    # Gain αναλογικού όρου — πόσο "επιθετικά" διορθώνει
Kd         = 15000   # Gain παράγωγου όρου  — αντιστέκεται στις απότομες αλλαγές
THRESHOLD  = 0       # Κατώφλι ADC για μαύρο/λευκό (υπολογίζεται στο calibration)

last_error     = 0   # Αποθηκεύει το προηγούμενο σφάλμα (για τον D όρο)
last_direction = 0   # Αποθηκεύει την τελευταία κατεύθυνση (για recovery)


# =============================================================================
# ΣΥΝΑΡΤΗΣΗ: set_motor_speed
# Ορίζει την ταχύτητα και κατεύθυνση και των δύο κινητήρων.
# Δέχεται τιμές από -65535 (πλήρης όπισθεν) έως +65535 (πλήρης εμπρός).
# =============================================================================
def set_motor_speed(left, right):
    # Περιορισμός τιμών εντός αποδεκτού εύρους
    left  = max(-65535, min(65535, int(left)))
    right = max(-65535, min(65535, int(right)))

    # Κινητήρας Α (Αριστερά)
    if left >= 0:
        motorA_in1.duty_u16(left)       # Εμπρός
        motorA_in2.duty_u16(0)
    else:
        motorA_in1.duty_u16(0)
        motorA_in2.duty_u16(abs(left))  # Πίσω

    # Κινητήρας Β (Δεξιά)
    if right >= 0:
        motorB_in1.duty_u16(right)       # Εμπρός
        motorB_in2.duty_u16(0)
    else:
        motorB_in1.duty_u16(0)
        motorB_in2.duty_u16(abs(right))  # Πίσω


# =============================================================================
# ΣΥΝΑΡΤΗΣΗ: median3
# Επιστρέφει τη διάμεσο (median) τριών τιμών.
# Χρησιμοποιείται για φιλτράρισμα θορύβου στις μετρήσεις ADC.
# =============================================================================
def median3(a, b, c):
    if a <= b <= c or c <= b <= a: return b
    if b <= a <= c or c <= a <= b: return a
    return c


# =============================================================================
# ΣΥΝΑΡΤΗΣΗ: read_adc_stable
# Διαβάζει έναν αναλογικό αισθητήρα 3 φορές και επιστρέφει τη διάμεσο.
# Έτσι μειώνουμε τον ηλεκτρικό θόρυβο χωρίς βαρύτερες μεθόδους.
# =============================================================================
def read_adc_stable(adc):
    a = adc.read_u16()
    b = adc.read_u16()
    c = adc.read_u16()
    return median3(a, b, c)


# =============================================================================
# ΣΥΝΑΡΤΗΣΗ: get_sensors
# Διαβάζει και τους 5 αισθητήρες και επιστρέφει λίστα [v1, v2, v3, v4, v5].
# Κάθε τιμή: 1 = βλέπει μαύρο (πάνω στη γραμμή)
#             0 = βλέπει λευκό (εκτός γραμμής)
# =============================================================================
def get_sensors():
    r2 = read_adc_stable(ir2)
    r3 = read_adc_stable(ir3)
    r4 = read_adc_stable(ir4)

    # Ψηφιακοί αισθητήρες: value()==0 σημαίνει ενεργός (PULL_UP λογική)
    v1 = 1 if ir1.value() == 0 else 0

    # Αναλογικοί: τιμή κάτω από THRESHOLD → μαύρο
    v2 = 1 if r2 < THRESHOLD else 0
    v3 = 1 if r3 < THRESHOLD else 0
    v4 = 1 if r4 < THRESHOLD else 0

    v5 = 1 if ir5.value() == 0 else 0

    return [v1, v2, v3, v4, v5]


# =============================================================================
# CALIBRATION — Βαθμονόμηση αισθητήρων
# Μετράμε τις τιμές ADC για μαύρο και λευκό ώστε να υπολογίσουμε αυτόματα
# το κατάλληλο THRESHOLD πριν ξεκινήσει το ρομπότ.
# Τοποθέτησε: IR3 πάνω στη μαύρη γραμμή, IR2 & IR4 πάνω στο λευκό.
# =============================================================================
set_motor_speed(0, 0)
print("CALIBRATION: 3 δευτερόλεπτα!")
print("Βάλε IR3 στο μαύρο, IR2/IR4 στο λευκό...")
time.sleep(3)

print("Διαβάζω τιμές...")
sum_black = 0
sum_white = 0
samples   = 100  # Αριθμός δειγμάτων για αξιόπιστο μέσο όρο

for _ in range(samples):
    sum_black += read_adc_stable(ir3)
    sum_white += (read_adc_stable(ir2) + read_adc_stable(ir4)) / 2
    time.sleep(0.01)

avg_black = sum_black / samples
avg_white = sum_white / samples

# Το threshold τοποθετείται στο 30% μεταξύ μαύρου και λευκού
# (πιο κοντά στο μαύρο για να αποφύγουμε ψευδείς ανιχνεύσεις)
THRESHOLD = int(avg_black + (avg_white - avg_black) * 0.3)

print(f"avg_black: {avg_black}")
print(f"avg_white: {avg_white}")
print(f"THRESHOLD: {THRESHOLD}")
print("Εκκίνηση σε 2 δευτερόλεπτα!")
time.sleep(2)

set_motor_speed(base_speed, base_speed)
time.sleep(0.1)

# =============================================================================
# ΚΥΡΙΟΣ ΒΡΟΧΟΣ (MAIN LOOP)
# Τρέχει συνεχώς και: διαβάζει αισθητήρες → υπολογίζει σφάλμα → διορθώνει
# =============================================================================
print_counter = 0  # Μετρητής για περιοδική εκτύπωση debug

try:
    while True:
        vals = get_sensors()  # Διαβάζουμε τους 5 αισθητήρες → [v1..v5]

        # Εκτύπωση debug κάθε 100 επαναλήψεις (για να μην επιβραδύνει)
        print_counter += 1
        if print_counter >= 100:
            print(f"VALS:{vals} | THR:{THRESHOLD}")
            print_counter = 0

        # -----------------------------------------------------------------
        # ΑΝΙΧΝΕΥΣΗ ΔΙΑΣΤΑΥΡΩΣΗΣ / ΕΜΠΟΔΙΟΥ
        # Αν >3 αισθητήρες βλέπουν μαύρο → σταματάμε (διασταύρωση ή τέλος)
        # -----------------------------------------------------------------
        if sum(vals) > 3:
            set_motor_speed(0, 0)
            print("STOP: >3 αισθητήρες στο μαύρο!")
            time.sleep(10)
            print("Συνέχεια...")
            set_motor_speed(base_speed, base_speed)
            time.sleep(0.1)
            continue

        # -----------------------------------------------------------------
        # ΕΝΤΟΠΙΣΜΟΣ ΤΕΛΕΥΤΑΙΑΣ ΚΑΤΕΥΘΥΝΣΗΣ
        # Αποθηκεύεται για χρήση στο recovery όταν χαθεί η γραμμή
        # -----------------------------------------------------------------
        if vals[0] == 1 or vals[1] == 1:
            last_direction = -1  # Η γραμμή ήταν αριστερά
        if vals[3] == 1 or vals[4] == 1:
            last_direction = 1   # Η γραμμή ήταν δεξιά

        # -----------------------------------------------------------------
        # ΥΠΟΛΟΓΙΣΜΟΣ ΣΦΑΛΜΑΤΟΣ (weighted average)
        # Βάρη αισθητήρων: [-2, -1, 0, +1, +2]
        # Αρνητικό = εκτροπή αριστερά, Θετικό = εκτροπή δεξιά
        # -----------------------------------------------------------------
        weights = [-2, -1, 0, 1, 2]
        error  = 0
        active = 0  # Πόσοι αισθητήρες βλέπουν μαύρο

        for i in range(5):
            if vals[i] == 1:
                error  += weights[i]
                active += 1

        # -----------------------------------------------------------------
        # ΑΠΟΦΑΣΕΙΣ ΚΙΝΗΣΗΣ
        # -----------------------------------------------------------------
        if active == 0:
            # Κανένας αισθητήρας δεν βλέπει γραμμή → RECOVERY
            # Στρίβουμε επί τόπου προς την τελευταία γνωστή κατεύθυνση
            if last_direction == 1:
                set_motor_speed(22000, -22000)   # Στροφή δεξιά επί τόπου
            else:
                set_motor_speed(-22000, 22000)   # Στροφή αριστερά επί τόπου

        elif active == 5:
            # Όλοι οι αισθητήρες βλέπουν μαύρο → πλήρης στάση (ασφάλεια)
            set_motor_speed(0, 0)

        else:
            # Κανονική λειτουργία → εφαρμογή PD controller
            current_error = error / active  # Κανονικοποιημένο σφάλμα

            # Dead zone: μικρά σφάλματα αγνοούνται (αποφυγή τρεμοπαίγματος)
            if abs(current_error) < 0.5:
                current_error = 0

            # Δυναμική ενίσχυση σε έντονες στροφές (|error| >= 1.5)
            # Αυξάνουμε P και D για πιο γρήγορη αντίδραση
            if abs(current_error) >= 1.5:
                P = (Kp * 1.8) * current_error
                D = (Kd * 2.0) * (current_error - last_error)
            else:
                P = Kp * current_error
                D = Kd * (current_error - last_error)

            correction = int(P + D)

            # Εφαρμογή διόρθωσης στους κινητήρες:
            # correction > 0 → στροφή δεξιά  (αριστερός πιο γρήγορος)
            # correction < 0 → στροφή αριστερά (δεξιός πιο γρήγορος)
            set_motor_speed(base_speed + correction, base_speed - correction)

            last_error = current_error  # Αποθήκευση για επόμενη επανάληψη

        time.sleep(0.0005)  # Μικρή καθυστέρηση για σταθερότητα βρόχου (~2kHz)

except KeyboardInterrupt:
    # Ασφαλής τερματισμός με Ctrl+C
    set_motor_speed(0, 0)
